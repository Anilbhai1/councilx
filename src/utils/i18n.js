const DYNAMIC_CACHE_PREFIX = '@councilx_lang_cache_';

async function fetchDynamicTranslation(text, targetLang) {
  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=${targetLang}&dt=t&q=${encodeURIComponent(text)}`;
    const res = await fetch(url);
    if (res.ok) {
      const data = await res.json();
      if (data && data[0] && data[0][0] && data[0][0][0]) {
        return data[0].map(item => item[0]).join('');
      }
    }
  } catch (e) {}
  return text;
}

export async function loadOrFetchDynamicTranslations(langCode) {
  if (TRANSLATIONS[langCode]) {
    return TRANSLATIONS[langCode];
  }

  try {
    const cached = await AsyncStorage.getItem(`${DYNAMIC_CACHE_PREFIX}${langCode}`);
    if (cached) {
      const parsed = JSON.parse(cached);
      TRANSLATIONS[langCode] = parsed;
      return parsed;
    }
  } catch (e) {}

  const baseDict = TRANSLATIONS.en;
  const newDict = { ...baseDict, categories: { ...baseDict.categories } };

  try {
    const keysToTranslate = [
      'brandSubtitle', 'supremeCouncilTitle', 'supremeCouncilBadge', 'supremeCouncilDesc',
      'searchPlaceholder', 'tabAll', 'tabBharat', 'tabModern', 'tabCustom',
      'counselBtn', 'chatInputPlaceholder', 'send', 'listen', 'stopListen',
      'createCustomAgentBtn', 'createAgentModalTitle', 'nameInputLabel',
      'fetchIntelligence', 'livePreviewTitle', 'createAndChatBtn',
      'profileTitle', 'logout', 'subscriptionStatus', 'renewPlanBtn',
      'buyPlanBtn', 'validUntil', 'daysLeft', 'referralTitle', 'yourCode',
      'selectLanguage', 'close'
    ];

    await Promise.all(
      keysToTranslate.map(async (key) => {
        if (baseDict[key]) {
          const translated = await fetchDynamicTranslation(baseDict[key], langCode);
          if (translated) newDict[key] = translated;
        }
      })
    );

    TRANSLATIONS[langCode] = newDict;
    await AsyncStorage.setItem(`${DYNAMIC_CACHE_PREFIX}${langCode}`, JSON.stringify(newDict));
  } catch (err) {
    TRANSLATIONS[langCode] = newDict;
  }

  return newDict;
}

